/** 菜单/帮助识别词（中文、英文与全角问号；大小写不敏感）。 */
const HELP_WORDS = new Set(['帮助', '菜单', 'help', '?', '？'])

/**
 * 是否是帮助请求。
 *
 * @param {string} text
 */
export function isHelpRequest(text: string): boolean {
  return HELP_WORDS.has(text.trim().toLowerCase())
}

